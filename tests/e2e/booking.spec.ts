import { expect, test, type Page } from '@playwright/test';

/**
 * Phase 3 acceptance journey through the real UI, API, MongoDB, Redis/BullMQ workers and the
 * labelled sandbox gateway (no real money): search → select a room → hold → guest details →
 * pay → verified confirmation → invoice download → cancel within the free window → refund
 * confirmed by the provider. A second test covers a declined card and a successful retry.
 * Requires seed data (`npm run seed`) and PAYMENT_PROVIDER=sandbox.
 */
const PASSWORD = 'E2e-Str0ng-Passw0rd';
const todayIst = () =>
  new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(new Date());
const addDays = (date: string, n: number) =>
  new Date(Date.parse(`${date}T00:00:00Z`) + n * 86_400_000).toISOString().slice(0, 10);
let counter = 0;
const uniqueEmail = () => `booker.${Date.now()}.${(counter += 1)}@example.com`;

async function register(page: Page) {
  await page.goto('/register');
  await page.getByLabel(/^First name/).fill('Meera');
  await page.getByLabel(/^Last name/).fill('Iyer');
  await page.getByLabel(/^Email/).fill(uniqueEmail());
  await page.getByLabel(/^Password\*?$/).fill(PASSWORD);
  await page.getByLabel(/^Confirm password/).fill(PASSWORD);
  await page.getByRole('checkbox', { name: /I agree/ }).check();
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page).toHaveURL(/\/account$/);
}

/** Search Goa for the given nights out, open the first result and continue with a free-cancellation rate. */
async function selectStay(page: Page, startOffset: number) {
  const checkIn = addDays(todayIst(), startOffset);
  const checkOut = addDays(checkIn, 2);
  await page.goto(`/hotels?destination=goa&checkIn=${checkIn}&checkOut=${checkOut}`);
  const first = page.getByRole('article').first();
  await expect(first).toContainText('₹');
  await first.getByRole('heading', { level: 3 }).getByRole('link').click();
  const offer = page
    .locator('li')
    .filter({ hasText: /Free cancellation until/ })
    .first();
  await offer.getByRole('button', { name: 'Select' }).click();
  await page
    .getByRole('complementary', { name: 'Booking summary' })
    .getByRole('button', { name: 'Continue to booking' })
    .click();
  await expect(page).toHaveURL(/\/checkout\?quote=/);
  await expect(page.getByText(/Rooms held for \d+:\d\d/)).toBeVisible({ timeout: 20_000 });
  await page.getByLabel(/^Mobile number/).fill('+919811111111');
  await page.getByRole('checkbox', { name: /booking terms/ }).check();
  await page.getByRole('button', { name: 'Continue to payment' }).click();
  await expect(page).toHaveURL(/\/checkout\/payment\?booking=SS-/);
  await page.getByRole('button', { name: /^Pay ₹/ }).click();
  await expect(page.getByText('Test payment sandbox — no real money moves')).toBeVisible();
}

test('book, pay, download the invoice, cancel and get refunded', async ({ page }) => {
  test.slow();
  await register(page);
  await selectStay(page, 25);
  await page.getByRole('button', { name: 'Simulate successful payment' }).click();
  await expect(page).toHaveURL(/\/checkout\/confirmation\?booking=SS-/);
  await expect(page.getByText('Your stay is confirmed')).toBeVisible({ timeout: 20_000 });
  const reference = new URL(page.url()).searchParams.get('booking')!;

  // The invoice is generated by the outbox worker; retry the download until it exists.
  await expect(async () => {
    const download = page.waitForEvent('download', { timeout: 5_000 });
    await page.getByRole('button', { name: 'Invoice (PDF)' }).click();
    expect((await download).suggestedFilename()).toMatch(/^SSI-\d{4}-\d{6}\.pdf$/);
  }).toPass({ timeout: 30_000 });

  await page.getByRole('link', { name: 'View booking' }).click();
  await expect(page).toHaveURL(new RegExp(`/account/bookings/${reference}$`));
  await page.getByRole('button', { name: 'Cancel booking' }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByText('Refund', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Cancel booking' }).click();
  await expect(page.getByText('Booking cancelled').first()).toBeVisible();

  // The refund is processed by the worker and marked complete only after the provider confirms.
  await expect(async () => {
    await page.reload();
    await expect(page.getByText('Refunded').first()).toBeVisible({ timeout: 2_000 });
  }).toPass({ timeout: 30_000 });
  await page.goto('/account/refunds');
  await expect(page.getByRole('listitem').filter({ hasText: reference })).toContainText('Refunded');
  await page.goto('/account');
  await expect(page.getByRole('heading', { name: 'Hello, Meera' })).toBeVisible();
});

test('a declined card can be retried while the rooms are held', async ({ page }) => {
  test.slow();
  await register(page);
  await selectStay(page, 40);
  await page.getByRole('button', { name: 'Simulate declined card' }).click();
  await expect(page).toHaveURL(/\/checkout\/failure\?booking=SS-/);
  await expect(page.getByRole('heading', { name: 'Your payment didn’t go through' })).toBeVisible();
  await page.getByRole('link', { name: 'Try again' }).click();
  await page.getByRole('button', { name: /^Pay ₹/ }).click();
  await page.getByRole('button', { name: 'Simulate successful payment' }).click();
  await expect(page.getByText('Your stay is confirmed')).toBeVisible({ timeout: 20_000 });
});
