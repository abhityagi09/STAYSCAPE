#!/usr/bin/env node
/**
 * Writes .env.staging for a self-contained staging stack (docker-compose.prod.yml --profile
 * self-hosted) with freshly generated secrets. The file is git-ignored and never printed.
 *
 *   node scripts/make-staging-env.mjs [--url=http://localhost:8081] [--force]
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const arg = (name, fallback) =>
  process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? fallback;
const url = arg('url', 'http://localhost:8081');
const file = '.env.staging';
if (existsSync(file) && !process.argv.includes('--force')) {
  console.log(`${file} exists; keeping it (pass --force to regenerate).`);
  process.exit(0);
}
const secret = () => randomBytes(36).toString('base64url');
const lines = {
  STACK_NAME: 'staging',
  DEPLOYMENT_ENV: 'staging',
  PUBLIC_URL: url,
  WEB_BIND: `127.0.0.1:${new URL(url).port || 80}`,
  MONGO_URI: 'mongodb://mongo:27017/stayscape?replicaSet=rs0',
  REDIS_URL: 'redis://redis:6379',
  JWT_ACCESS_SECRET: secret(),
  DATA_ENCRYPTION_KEY: secret(),
  QUOTE_SIGNING_SECRET: secret(),
  SANDBOX_PAYMENT_SECRET: secret(),
  METRICS_TOKEN: secret(),
  // Browsers treat http://localhost as a secure context, so Secure cookies work for local staging.
  COOKIE_SECURE: 'true',
  PAYMENT_PROVIDER: 'sandbox',
  SMTP_HOST: 'mailpit',
  SMTP_PORT: '1025',
  STORAGE_DRIVER: 'local',
  API_DOCS_ENABLED: 'false',
  IMAGE_TAG: 'staging',
  BACKUP_MONGO_URI: 'mongodb://mongo:27017/?replicaSet=rs0',
  BACKUP_PASSPHRASE: secret(),
  // Automated suites (e2e, k6) run from one IP; production keeps the lower defaults.
  RATE_LIMIT_MAX: '100000',
  AUTH_RATE_LIMIT_MAX: '5000',
  LOGIN_RATE_LIMIT_MAX: '5000',
};
writeFileSync(
  file,
  `# Generated by scripts/make-staging-env.mjs — staging only, never commit.\n${Object.entries(
    lines,
  )
    .map(([k, v]) => `${k}=${v}`)
    .join('\n')}\n`,
  { mode: 0o600 },
);
console.log(`Wrote ${file} for ${url}.`);
